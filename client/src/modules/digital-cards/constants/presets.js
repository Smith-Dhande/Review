const loadedFontSet = new Set()
export function loadCardFonts(fonts = []) {
  if (typeof document === 'undefined') return
  const needed = [...new Set(fonts.filter(Boolean))].filter(
    (f) => !loadedFontSet.has(f),
  )
  if (!needed.length) return
  for (const f of needed) loadedFontSet.add(f)
  const families = needed
    .map((f) => `family=${encodeURIComponent(f)}:wght@400;500;600;700`)
    .join('&')
  const link = document.createElement('link')
  link.rel = 'stylesheet'
  link.href = `https://fonts.googleapis.com/css2?${families}&display=swap`
  document.head.appendChild(link)
}

export function getCardFontStack(fontName) {
  const serif = [
    'Playfair Display',
    'Cormorant Garamond',
    'Cinzel',
    'Fraunces',
    'DM Serif Display',
    'Bodoni Moda',
    'Lora',
  ].includes(fontName)
  const mono = fontName === 'JetBrains Mono'
  if (mono) {
    return `'JetBrains Mono', ui-monospace, SFMono-Regular, Menlo, monospace`
  }
  return `'${fontName || 'Inter'}', ${serif ? 'Georgia, serif' : 'system-ui, -apple-system, sans-serif'}`
}

export function getDigitalCardPublicUrl(card) {
  const slug = card?.slug || card?.id || ''
  const configured = import.meta.env.VITE_PUBLIC_APP_URL?.trim()
  if (configured) {
    return `${configured.replace(/\/+$/, '')}/card/${slug}`
  }
  const stored = card?.publicUrl || ''
  if (stored && !/localhost|127\.0\.0\.1/i.test(stored)) {
    return stored
  }
  const base =
    (typeof window !== 'undefined' && window.location?.origin) ||
    'https://reviewbuddy.com'
  return `${base.replace(/\/+$/, '')}/card/${slug}`
}
